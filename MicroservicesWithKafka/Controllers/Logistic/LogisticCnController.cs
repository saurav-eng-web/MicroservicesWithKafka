using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using MicroservicesWithKafka.Models.Logistic;
using MicroservicesWithKafka.Services.Logistic;
using Microsoft.Extensions.Logging;
using System;
using System.Collections.Generic;
using System.Threading.Tasks;

namespace MicroservicesWithKafka.Controllers.Logistic
{
    /// <summary>CN Logistic uploader. Replaces Logistic/CNLogisticUploader.aspx.vb.</summary>
    [Authorize(Policy = "LogisticPolicy")]
    [Route("api/logistic/cn")]
    [ApiController]
    public class LogisticCnController : ControllerBase
    {
        private readonly ILogisticCnService _service;
        private readonly ILogger<LogisticCnController> _logger;

        public LogisticCnController(ILogisticCnService service, ILogger<LogisticCnController> logger)
        {
            _service = service;
            _logger = logger;
        }

        /// <summary>
        /// Uploads CN rows (CNno, dispatchWarehouse, docketNo, dispatchstatus): bulk copy into CNLogisticUploader,
        /// stamp createdBy with the logged-in user, then run CNTracking — as the legacy btnUpload did.
        /// </summary>
        [HttpPost("upload")]
        public async Task<IActionResult> Upload([FromBody] List<CnLogisticUploadViewModel> rows)
        {
            if (rows == null || rows.Count == 0)
                return BadRequest(new { message = "No rows provided." });

            var userId = User.FindFirst("UserID")?.Value ?? string.Empty;
            try
            {
                var result = await _service.UploadAsync(rows, userId);
                return result.Success ? Ok(new { message = result.Message }) : BadRequest(new { message = result.Message });
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "CN logistic upload failed");
                return StatusCode(500, new { message = "Failed to upload CN data. Please try again or contact support." });
            }
        }

        /// <summary>
        /// Legacy Search: no ticketNo -> all rows of CNLogisticUploader (CNno, dispatchWarehouse, dispatchstatus);
        /// ticketNo ("Enter Job") -> AutoGeneratedChallan (TicketNo, Partcode).
        /// </summary>
        [HttpGet]
        public async Task<IActionResult> Search([FromQuery] string? ticketNo)
        {
            try
            {
                return Ok(await _service.SearchAsync(ticketNo));
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "CN logistic search failed");
                return StatusCode(500, new { message = "Failed to load CN data. Please try again or contact support." });
            }
        }
    }
}
